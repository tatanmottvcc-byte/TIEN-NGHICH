"""Read alpha bounds only; never changes the generated PNGs. Requires Pillow."""
from pathlib import Path
import json
from PIL import Image
import numpy as np
from scipy import ndimage
ROOT=Path(__file__).resolve().parents[1]
names=['male','female','wolf','fox','boar','bear','wisp','treant','npc','maleAttack','femaleAttack']
result={}
for name in names:
 file=name+('-v2.png' if name.endswith('Attack') else '-idle-v1.png' if name=='npc' else '-walk-v1.png')
 path=ROOT/'public/assets/sprites'/file
 if not path.exists():continue
 im=Image.open(path);w,h=im.size;alpha=im.getchannel('A').point(lambda v:255 if v>100 else 0)
 cols=4 if name=='npc' else 8
 # Locate the quietest separator near each nominal grid boundary.
 def boundary(axis,nominal,radius):
  lo,hi=max(1,nominal-radius),min((w if axis==0 else h)-1,nominal+radius)
  scores=[]
  for i in range(lo,hi):
   strip=alpha.crop((i,0,i+1,h) if axis==0 else (0,i,w,i+1))
   count=strip.histogram()[255]
   scores.append((count,abs(i-nominal),i))
  return min(scores)[2]
 xs=[0]+[boundary(0,int(i*w/cols),40) for i in range(1,cols)]+[w]
 ys=[0]+[boundary(1,int(i*h/4),35) for i in range(1,4)]+[h]
 frames=[]
 for row in range(4):
  for col in range(cols):
   box=(xs[col],ys[row],xs[col+1],ys[row+1]);cell=alpha.crop(box);b=cell.getbbox()
   if name.endswith('Attack'):
    labels,count=ndimage.label(np.asarray(cell)>0,structure=np.ones((3,3)))
    areas=np.bincount(labels.ravel());areas[0]=0
    component=ndimage.find_objects(labels)[int(areas.argmax())-1]
    yy,xx=component;b=(xx.start,yy.start,xx.stop,yy.stop)
   if not b:raise ValueError((name,row,col))
   # Bounded two-pixel margin preserves antialiasing.
   l,t,r,bottom=b;x=max(box[0],box[0]+l-2);y=max(box[1],box[1]+t-2)
   frames.append(dict(x=x,y=y,w=min(box[2],box[0]+r+2)-x,h=min(box[3],box[1]+bottom+2)-y))
 result[name]=dict(file=file,width=w,height=h,columns=cols,frames=frames)
 if name=='wolf':result[name]['directions']=[0,1,6,3,4,5,2,7]
 print(name,xs,ys)
(ROOT/'public/sprite-atlas.js').write_text('// Alpha bounds measured from original PNGs; generated by tools/index-sprites.py.\nexport const ATLAS='+json.dumps(result,separators=(',',':'))+';\n')
